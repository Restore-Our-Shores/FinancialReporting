test_that("deployment uses the repository root and always includes its lockfile", {
  root <- normalizePath(testthat::test_path("..", ".."), winslash = "/")
  helper <- file.path(root, "dev", "deploy.R")
  skip_if_not(file.exists(helper))
  helpers <- new.env(parent = globalenv())
  source(helper, local = helpers)
  original <- getwd()
  setwd(tempdir())
  plan <- tryCatch(helpers$deploy_financialreports(dry_run = TRUE), finally = setwd(original))
  expect_identical(plan$appDir, root)
  expect_true("renv.lock" %in% plan$appFiles)
  expect_true(file.exists(plan$lockfile))
  expect_false(any(grepl("^(data|quarters|reports|renv)/", plan$appFiles)))
  empty <- tempfile(); dir.create(empty)
  expect_error(helpers$deploy_financialreports(appDir = empty, dry_run = TRUE), "renv.lock was not found")
})
